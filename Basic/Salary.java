import java.util.*;
public class Salary{
    public static void main(String[]args){
        int salary = 30000;
        // After + 5000
        salary += 5000;
        // after -2000
        salary -= 2000;
        // after *2
        salary *= 2; 
        // after /3
        salary /= 3;

        System.out.println(salary);
    }
}